/** A lookup from object id to object. */
export type ObjectLookup = (oid: string) => GitObject | undefined;

/**
 * True when `ancestor` is reachable from `descendant` by following commit parents (and tag
 * targets). Walks only the commit graph — never trees or blobs — and stops as soon as `ancestor`
 * is found, so a fast-forward check on a long linear history is O(distance), not O(history).
 */
export function isAncestor(ancestor: string, descendant: string, lookup: ObjectLookup): boolean {
  if (ancestor === descendant) return true;
  const seen = new Set<string>();
  const queue: string[] = [descendant];
  while (queue.length) {
    const oid = queue.pop()!;
    if (oid === ancestor) return true;
    if (seen.has(oid)) continue;
    seen.add(oid);
    const object = lookup(oid);
    if (!object) continue;
    if (object.type === 'commit') {
      for (const parent of parseCommit(object.data).parents) queue.push(parent);
    } else if (object.type === 'tag') {
      queue.push(parseTag(object.data).object);
    }
  }
  return false;
}

/**
 * Every object reachable from `roots`: commit -> tree + parents, tree -> entries (gitlinks
 * skipped), tag -> its target, blob -> nothing. Throws on a missing object unless `allowMissing`.
 * `stopAt` commits are included as leaves: their parents are not followed (a client's shallow
 * boundary — it does not hold a shallow commit's parents).
 */
export function collectReachable(
  roots: Iterable<string>,
  lookup: ObjectLookup,
  options: { allowMissing?: boolean; stopAt?: ReadonlySet<string> } = {},
): Set<string> {
  const seen = new Set<string>();
  const queue: string[] = [];
  for (const root of roots) if (isObjectId(root)) queue.push(root);
  while (queue.length) {
    const oid = queue.pop()!;
    if (seen.has(oid)) continue;
    const object = lookup(oid);
    if (!object) {
      if (options.allowMissing) continue;
      throw new Error(`object ${oid} is missing from the store`);
    }
    seen.add(oid);
    if (object.type === 'commit') {
      const commit = parseCommit(object.data);
      queue.push(commit.tree);
      if (!options.stopAt?.has(oid)) for (const parent of commit.parents) queue.push(parent);
    } else if (object.type === 'tag') {
      queue.push(parseTag(object.data).object);
    } else if (object.type === 'tree') {
      for (const entry of parseTree(object.data)) {
        if (entry.mode === '160000') continue;
        queue.push(entry.oid);
      }
    }
  }
  return seen;
}

export interface DepthWalk {
  /** Every object reachable within the depth limit (commits of generation < depth, their trees/blobs). */
  readonly objects: Set<string>;
  /** The commits at generation depth-1: the new shallow boundary. Empty when depth is unlimited. */
  readonly boundary: string[];
  /** The old boundary commits that are now interior (their parents were followed): no longer shallow. */
  readonly unshallow: string[];
  /** The generation of each included commit (0 = a want). */
  readonly generations: Map<string, number>;
}

/**
 * The depth-limited closure of `roots`: commits of generation < `depth` (generation 0 is a root),
 * plus each included commit's tree and blobs. `depth` null means no limit. The boundary is the
 * set of commits at generation depth-1. The depth limit alone controls the walk: a commit in
 * `stopAt` (the client's old shallow boundary) is still followed, because a deepen must reach
 * one generation past it — `stopAt` only marks which old boundary commits are now interior
 * (`unshallow`). The have-closure (what the client already holds) is a separate concern and
 * does stop at `stopAt`; see `collectReachable`.
 */
export function collectDepthLimited(
  roots: Iterable<string>,
  lookup: ObjectLookup,
  depth: number | null,
  stopAt: ReadonlySet<string> = new Set(),
): DepthWalk {
  const objects = new Set<string>();
  const generations = new Map<string, number>();
  const boundary: string[] = [];
  // BFS over commits by generation, so the boundary is exact.
  const queue: Array<{ oid: string; generation: number }> = [];
  for (const root of roots) {
    if (!isObjectId(root) || generations.has(root)) continue;
    generations.set(root, 0);
    queue.push({ oid: root, generation: 0 });
  }
  const includeClosure = (oid: string): void => {
    // One commit's own content: the commit, its tree and its blobs — never its parents.
    const queue: string[] = [oid];
    while (queue.length) {
      const current = queue.pop()!;
      if (objects.has(current)) continue;
      const object = lookup(current);
      if (!object) continue;
      objects.add(current);
      if (object.type === 'commit') {
        queue.push(parseCommit(object.data).tree);
      } else if (object.type === 'tag') {
        queue.push(parseTag(object.data).object);
      } else if (object.type === 'tree') {
        for (const entry of parseTree(object.data)) {
          if (entry.mode === '160000') continue;
          queue.push(entry.oid);
        }
      }
    }
  };
  while (queue.length) {
    const { oid, generation } = queue.shift()!;
    const object = lookup(oid);
    if (!object) continue;
    if (object.type === 'tag') {
      // A wanted tag: include it and walk its target at the same generation.
      objects.add(oid);
      const target = parseTag(object.data).object;
      if (isObjectId(target) && !generations.has(target)) {
        generations.set(target, generation);
        queue.push({ oid: target, generation });
      }
      continue;
    }
    if (object.type !== 'commit') {
      objects.add(oid);
      continue;
    }
    includeClosure(oid);
    if (depth !== null && generation === depth - 1) {
      boundary.push(oid);
      continue;
    }
    const commit = parseCommit(object.data);
    for (const parent of commit.parents) {
      if (!generations.has(parent)) {
        generations.set(parent, generation + 1);
        queue.push({ oid: parent, generation: generation + 1 });
      }
    }
  }
  const unshallow: string[] = [];
  for (const oid of stopAt) {
    const generation = generations.get(oid);
    if (generation !== undefined && (depth === null || generation < depth - 1)) unshallow.push(oid);
  }
  return { objects, boundary, unshallow, generations };
}

/** The commit timestamp (author line), or 0 when unparseable. */
export function commitTimestamp(data: Uint8Array): number {
  try {
    const commit = parseCommit(data);
    const match = / (\d+) [+-]\d{4}$/.exec(commit.author);
    return match ? Number(match[1]) : 0;
  } catch {
    return 0;
  }
}
